const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

function normalize(value) {
  return value
    .normalize("NFKD")
    .toLowerCase()
    .replace(/[''`´’‘]/g, "")
    .replace(/gokshu?ru/g, "gokhru")
    .replace(/para\s*aminobenzoic\s*acid/g, "paraaminobenzoicacid")
    .replace(/vitamin\s+/g, "vitamin")
    .replace(/\s*\+\s*/g, "+")
    .replace(/\s+/g, "")
    .replace(/[^a-z0-9+]/g, "");
}

function stem(filename) {
  return filename.replace(/\.(jpe?g|png|webp|avif)$/i, "");
}

function isNamedProductFile(filename) {
  if (!/\.(jpe?g|png|webp|avif)$/i.test(filename)) return false;
  if (/^magnific_/i.test(filename)) return false;
  if (/^[0-9a-f-]{8,}\./i.test(filename)) return false;
  if (/^\d+\.(jpe?g|png|webp|avif)$/i.test(filename)) return false;
  return true;
}

function listImages(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter(isNamedProductFile);
}

function findFile(files, formula) {
  const want = normalize(formula);
  const exact = files.find((file) => normalize(stem(file)) === want);
  if (exact) return exact;

  const wantTokens = new Set(want.split("+").filter(Boolean));
  let best = null;
  let bestScore = 0;
  for (const file of files) {
    const tokens = new Set(normalize(stem(file)).split("+").filter(Boolean));
    if (!tokens.size || !wantTokens.size) continue;
    let overlap = 0;
    for (const token of wantTokens) if (tokens.has(token)) overlap += 1;
    const score = overlap / Math.max(wantTokens.size, tokens.size);
    if (score > bestScore) {
      bestScore = score;
      best = file;
    }
  }
  return bestScore >= 0.92 ? best : null;
}

function writeManifest(outFile, exportName, manifest) {
  const body = Object.entries(manifest)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, url]) => `  ${JSON.stringify(key)}: ${JSON.stringify(url)},`)
    .join("\n");
  fs.writeFileSync(
    outFile,
    `/** Auto-generated by scripts/generate-range-manifests.mjs — do not edit by hand */\nexport const ${exportName}: Record<string, string> = {\n${body}\n};\n`,
  );
}

function generateRange({
  rangeFolder,
  outFile,
  exportName,
  folderByCategory,
  catalog,
}) {
  const imageRoot = path.join(root, "public/product-images", rangeFolder);
  const manifest = {};
  const missing = [];
  const folderCache = new Map();

  for (const [category, formulas] of catalog) {
    const folder = folderByCategory[category] ?? null;
    const dir = folder ? path.join(imageRoot, folder) : null;
    if (folder && !folderCache.has(folder)) {
      folderCache.set(folder, listImages(dir));
    }
    const files = folder ? folderCache.get(folder) : [];

    for (const formula of formulas) {
      const key = `${folder ?? category}|${formula}`;
      const filename = folder ? findFile(files, formula) : null;
      if (!filename) {
        missing.push(`${category} → ${formula}`);
        manifest[key] = "";
        continue;
      }
      manifest[key] = `/product-images/${rangeFolder}/${folder}/${filename}`;
    }
  }

  writeManifest(outFile, exportName, manifest);
  const matched = Object.values(manifest).filter(Boolean).length;
  const blank = Object.values(manifest).filter((url) => !url).length;
  console.log(
    `${rangeFolder}: ${matched} matched, ${blank} blank placeholders → ${path.relative(root, outFile)}`,
  );
  if (blank) {
    console.log("  blank:");
    for (const item of missing) console.log(`    ${item}`);
  }
}

